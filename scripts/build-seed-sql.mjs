// Writes supabase/seed.sql from the catalogue in shared/catalogue.js.
// Run: npm run seed:sql. Safe to run the SQL again: existing rows (matched by
// slug / SKU) are left untouched, so edits made in the admin screen are kept.
import fs from 'node:fs'
import { SEED_CATEGORIES, SEED_PRODUCTS, DEFAULT_SETTINGS } from '../shared/catalogue.js'

const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)
const j = (v) => `${q(JSON.stringify(v ?? []))}::jsonb`

const categories = SEED_CATEGORIES.map((c) => `  (${[c.slug, c.name, c.description, c.sort_order, c.icon].map(q).join(', ')})`)

const COLS = 'sku, slug, name, brand, category_id, short_description, long_description, specs, images, price_paise, gst_percent, hsn_code, stock_qty, min_order_qty, is_active, is_featured, quote_only, seo_title, seo_description'
const products = SEED_PRODUCTS.map((p) =>
  `  (${[
    q(p.sku), q(p.slug), q(p.name), q(p.brand), `(select id from categories where slug = ${q(p.category)})`,
    q(p.short_description), q(p.long_description || ''), j(p.specs), j(p.images), q(p.price_paise ?? null), q(p.gst_percent ?? 18),
    q(p.hsn_code || ''), q(p.stock_qty ?? 0), q(p.min_order_qty ?? 1), q(p.is_active !== false), q(Boolean(p.is_featured)),
    q(Boolean(p.quote_only)), q(p.seo_title || null), q(p.seo_description || null),
  ].join(', ')})`
)

// Products go in batches so the Supabase SQL editor handles the file comfortably.
const batches = []
for (let i = 0; i < products.length; i += 100) {
  batches.push(`insert into products (${COLS}) values\n${products.slice(i, i + 100).join(',\n')}\non conflict (sku) do nothing;`)
}

const sql = `-- Launch catalogue (no prices yet). Run after schema.sql.
-- Generated by scripts/build-seed-sql.mjs from shared/catalogue.js: do not edit by hand.
-- Safe to run again: existing products are left untouched; categories only get their menu order updated.

insert into categories (slug, name, description, sort_order, icon) values
${categories.join(',\n')}
on conflict (slug) do update set sort_order = excluded.sort_order;

${batches.join('\n\n')}

insert into settings (key, value) values ('shop', ${j(DEFAULT_SETTINGS)})
on conflict (key) do nothing;

-- Give yourself staff access (replace the email, then run this line):
-- insert into staff (email, name) values ('you@prosperinfotech.com', 'Your Name') on conflict (email) do nothing;
`

fs.writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log(`supabase/seed.sql: ${SEED_CATEGORIES.length} categories, ${SEED_PRODUCTS.length} products`)
